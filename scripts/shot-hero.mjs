import { chromium } from 'playwright';
const out = '/opt/cursor/artifacts';
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
await page.goto('http://localhost:3000/', { waitUntil: 'networkidle', timeout: 60000 });
await page.waitForTimeout(2800);
await page.screenshot({ path: `${out}/stan_only_hero_start.png`, fullPage: false });
await page.evaluate(() => window.scrollTo(0, Math.round(window.innerHeight * 1.15)));
await page.waitForTimeout(1100);
await page.screenshot({ path: `${out}/stan_only_hero_parallax.png`, fullPage: false });
await page.evaluate(() => document.querySelector('#achievements')?.scrollIntoView({behavior:'instant'}));
await page.waitForTimeout(900);
await page.screenshot({ path: `${out}/stan_only_titles_grid.png`, fullPage: false });
await browser.close();
console.log('done');
