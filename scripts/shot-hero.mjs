import { chromium } from 'playwright';
const out = '/opt/cursor/artifacts';
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
await page.goto('http://localhost:3000/', { waitUntil: 'networkidle', timeout: 60000 });
await page.waitForTimeout(2500);
await page.screenshot({ path: `${out}/stan_hero_real_start.png`, fullPage: false });
await page.evaluate(() => window.scrollTo(0, Math.round(window.innerHeight * 1.1)));
await page.waitForTimeout(1000);
await page.screenshot({ path: `${out}/stan_hero_real_scroll.png`, fullPage: false });
await page.evaluate(() => window.scrollTo(0, Math.round(window.innerHeight * 2.8)));
await page.waitForTimeout(1000);
await page.screenshot({ path: `${out}/stan_achievements_grid.png`, fullPage: false });
await browser.close();
console.log('done');
